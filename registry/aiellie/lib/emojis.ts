// The emoji the picker offers, by category, each with its name and other
// words it's found by. Hand-picked rather than the whole of Unicode: the ones
// chats use most, and nothing past Emoji 13, so current systems draw them all.

type Emoji = {
  emoji: string
  name: string
  /** Other words it's found by, besides those in its name. */
  keywords: string[]
}

type EmojiCategory = { id: string; label: string; emojis: Emoji[] }

type Row = [emoji: string, name: string, keywords?: string]

const rows = (list: Row[]): Emoji[] =>
  list.map(([emoji, name, keywords = ""]) => ({
    emoji,
    name,
    keywords: keywords.split(" ").filter(Boolean),
  }))

/** A country's flag from its two-letter code, as regional indicator letters. */
const flag = (code: string) =>
  String.fromCodePoint(
    ...[...code].map((letter) => 0x1f1a5 + letter.charCodeAt(0))
  )

