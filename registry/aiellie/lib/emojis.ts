const ALL = EMOJI_CATEGORIES.flatMap((category) => category.emojis)

// Every word of its name and keywords, lowercased, for the search to match
// the start of. "Upside-down" is two words, so "down" finds it.
const WORDS = new Map(
  ALL.map((each) => [
    each,
    [each.name, ...each.keywords]
      .join(" ")
      .toLowerCase()
      .split(/[\s-]+/)
      .filter(Boolean),
  ])
)

const BY_EMOJI = new Map(ALL.map((each) => [each.emoji, each]))

function findEmoji(emoji: string) {
  return BY_EMOJI.get(emoji)
}

/**
 * The emoji whose words start with every word of the query, in the order
 * they're browsed in. An emoji itself finds its own entry.
 */
function searchEmojis(query: string) {
  const terms = query.toLowerCase().split(/\s+/).filter(Boolean)
  if (terms.length === 0) return []
  return ALL.filter(
    (each) =>
      each.emoji === query.trim() ||
      terms.every((term) =>
        WORDS.get(each)!.some((word) => word.startsWith(term))
      )
  )
}

